import assert from 'node:assert/strict';
import {Queue,cleanResult,cleanState} from './gecko-broker.mjs';
const q=new Queue();
assert.throws(()=>q.enqueue('one','eval'),/invalid_command/);
const job=q.enqueue('one','scroll');
assert.throws(()=>q.enqueue('one','read'),/busy/);
assert.equal(q.poll('two',{}).command,null);
assert.equal(q.poll('one',{}).command.id,job.id);
assert.equal(q.poll('one',{}).command,null,'delivered scroll must not replay');
assert.throws(()=>q.result('two',{id:job.id,outcome:'completed'}),/unexpected_result/);
q.result('one',{id:job.id,outcome:'completed',cookie:'secret',snapshot:{scrollBefore:0,scrollAfter:50,password:'secret'}});
assert.equal(q.status('one').job.result.snapshot.scrollAfter,50);
assert.ok(!JSON.stringify(q.status('one')).includes('secret'));
const expired=q.enqueue('one','read',1000);assert.equal(q.poll('one',{},62000).command,null);
assert.equal(q.get('one').job.status,'expired');
q.enqueue('one','scroll',100000);q.poll('one',{},100001);q.poll('one',{},161000);
assert.equal(q.get('one').job.status,'delivery_outcome_unknown');
assert.deepEqual(cleanState({token:'secret',startReason:'secret'}),{});
assert.equal(cleanState({appVersion:'0.3.1'}).appVersion,'0.3.1');
assert.equal(cleanState({appVersion:'0.3'}).appVersion,'0.3');
assert.deepEqual(cleanState({appVersion:'0.3.1 secret'}),{});
assert.throws(()=>cleanResult({id:'bad',outcome:'completed'}),/invalid_result/);
console.log('Gecko broker queue/isolation/expiry/no-replay/redaction checks passed (simulated, no device or TLS test).');
